// 스테이지 데이터 (오리지널 레벨 디자인)
// 기호: # 블록  = 일방발판  ^ 가시  J 점프패드  H 불판  < > 컨베이어  C 부서지는 블록  I 버터
//       S 스위치  B 버저  D 문(빨강 켜지면 열림)  d 문(빨강 켜지면 닫힘)  Q 퀴즈 표지판  O X 정답·오답 패널
//       T 타이머 블록  W/w Y/y 워프 상자  R r 리듬 발판  g 숨은 발판  U 스포트라이트  Z 레이저  x 발판 정지점  ! 힌트
//       @ 시작  E 출구  K 체크포인트  * 보석  $ 황금 보석  ? 선물상자  a 파이 b 폭탄 c 마이크 e 자석 f 망토 h 스프링
//       1 마시멜로 2 핫소스 병 3 피망 버섯 4 물음표 봇 5 버저 두더지 6 디스코 댄서 7 카메라 드론 8 토마토 관객
//       m 가로 발판  n 세로 발판  o 미러볼 범퍼  9 보스  z 점령 구역

function build(h, fn) {
  const W = 260;
  const g = Array.from({ length: h }, () => Array(W).fill('.'));
  let w = 0;
  const L = {
    s(x, y, c) { if (x >= 0 && x < W && y >= 0 && y < h) { g[y][x] = c; if (x + 1 > w) w = x + 1; } },
    r(x0, y0, x1, y1, c) { for (let y = Math.min(y0, y1); y <= Math.max(y0, y1); y++) for (let x = Math.min(x0, x1); x <= Math.max(x0, x1); x++) L.s(x, y, c); },
    ground(x0, x1, top = 14) { L.r(x0, top, x1, h - 1, '#'); },
    width(n) { w = Math.max(w, n); },
  };
  fn(L);
  return g.map(r => r.slice(0, w).join(''));
}

